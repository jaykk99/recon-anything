def t_classify():
    v = classify_response(resp(403, {"cf-ray": "abc", "server": "cloudflare"},
                               CF_CHALLENGE))
    check("cf 403 challenge -> js-challenge/Cloudflare",
          v.kind == JS_CHALLENGE and v.vendor == "Cloudflare", f"{v.kind}/{v.vendor}")

    v = classify_response(resp(429, {"cf-ray": "abc"}, CF_1015))
    check("cf 429 1015 -> rate-limit/Cloudflare",
          v.kind == RATE_LIMIT and v.vendor == "Cloudflare", f"{v.kind}/{v.vendor}")

    v = classify_response(resp(403, {"akamai-origin-hop": "1"}, AKAMAI_403))
    check("akamai 403 -> waf/Akamai",
          v.kind == WAF and v.vendor == "Akamai", f"{v.kind}/{v.vendor}")

    v = classify_response(resp(403, {"x-iinfo": "1-2-3"}, IMPERVA_403))
    check("imperva 403 -> waf/Imperva",
          v.kind == WAF and v.vendor == "Imperva", f"{v.kind}/{v.vendor}")

    v = classify_response(resp(403, {"x-amz-cf-id": "abc=="}, AWS_CF_403))
    check("aws cloudfront 403 -> waf/AWS",
          v.kind == WAF and v.vendor and "AWS" in v.vendor, f"{v.kind}/{v.vendor}")

    v = classify_response(resp(403, {"x-datadome": "protected"}, DATADOME))
    check("datadome -> js-challenge/DataDome",
          v.kind == JS_CHALLENGE and v.vendor == "DataDome", f"{v.kind}/{v.vendor}")

    v = classify_response(resp(403, {}, "<html><body>nope</body></html>"))
    check("generic 403 -> blocked, no vendor",
          v.kind == BLOCKED and v.vendor is None, f"{v.kind}/{v.vendor}")
    v = classify_response(resp(403, {}, "<html><body>Forbidden</body></html>"))
    check("403 'forbidden' wording -> waf, no vendor",
          v.kind == WAF and v.vendor is None, f"{v.kind}/{v.vendor}")

    v = classify_response(resp(404, {}, "not here"))
    check("404 -> not-found", v.kind == NOT_FOUND, v.kind)

    v = classify_response(resp(500, {}, "internal error"))
    check("500 -> server-error", v.kind == SERVER_ERROR, v.kind)

    v = classify_response(resp(503, {"retry-after": "30"}, "slow down"))
    check("503 retry-after -> rate-limit", v.kind == RATE_LIMIT, v.kind)

    v = classify_response(resp(503, {"cf-ray": "abc"}, CF_CHALLENGE))
    check("503 cf challenge -> js-challenge", v.kind == JS_CHALLENGE, v.kind)

    v = classify_response(resp(200, {"cf-ray": "abc"}, "<html>ok</html>"))
    check("200 cf-ray -> clean, vendor attributed",
          v.kind == CLEAN and v.vendor == "Cloudflare", f"{v.kind}/{v.vendor}")

    v = classify_response(resp(200, {}, "<html>ok</html>",
                                   url="https://example.com/"))
    check("200 plain -> clean, no vendor",
          v.kind == CLEAN and v.vendor is None, f"{v.kind}/{v.vendor}")

    # legacy compat
    check("detect_protection 403 cf -> waf",
          detect_protection(resp(403, {"cf-ray": "a"}, CF_CHALLENGE)) in ("waf", "js-challenge"))
    check("detect_protection 429 -> rate-limit",
          detect_protection(resp(429, {}, "slow")) == "rate-limit")
    check("detect_protection 200 -> None",
          detect_protection(resp(200, {}, "ok")) is None)
    check("detect_protection 404 -> None",
          detect_protection(resp(404, {}, "nope")) is None)


def t_retry_after():
    check("retry-after seconds", parse_retry_after("30") == 30.0)
    import datetime as dti
    future = (dti.datetime.now(dti.timezone.utc) +
              dti.timedelta(seconds=60)).strftime("%a, %d %b %Y %H:%M:%S GMT")
    v = parse_retry_after(future)
    check("retry-after http-date ~60s", v is not None and 50 < v <= 61, str(v))
    check("retry-after garbage -> None", parse_retry_after("soon") is None)
    check("retry-after None -> None", parse_retry_after(None) is None)


def t_limiter_backoff():
    lim = RateLimiter(default_rps=25.0)
    host = "blocked.example"

    # vendor-attributed block: immediate graceful mode + rps floor
    lim.note_result(host, classify_response(
        resp(403, {"cf-ray": "a"}, CF_CHALLENGE, url=f"https://{host}/")))
    check("cf block -> waf_active", lim.waf_active(host))
    check("cf block -> vendor Cloudflare", lim.waf_vendor(host) == "Cloudflare")
    check("cf block -> rps dropped to floor",
          lim._rps[host] <= 1.0, str(lim._rps.get(host)))

    # generic 403s: need 3 to trip (single 403 may be a path ACL)
    lim2 = RateLimiter(default_rps=25.0)
    g = lambda: classify_response(resp(403, {}, "nope", url="https://g.example/"))
    lim2.note_result("g.example", g())
    lim2.note_result("g.example", g())
    check("2 generic 403s -> not active", not lim2.waf_active("g.example"))
    lim2.note_result("g.example", g())
    check("3 generic 403s -> active", lim2.waf_active("g.example"))
    check("3 generic 403s -> rps floored", lim2._rps["g.example"] <= 1.0)

    # clean / 404 / 500 never trigger
    lim3 = RateLimiter(default_rps=25.0)
    for _ in range(10):
        lim3.note_result("c.example", classify_response(
            resp(200, {}, "ok", url="https://c.example/")))
    lim3.note_result("c.example", classify_response(
        resp(404, {}, "x", url="https://c.example/")))
    lim3.note_result("c.example", classify_response(
        resp(500, {}, "x", url="https://c.example/")))
    check("clean host -> not active", not lim3.waf_active("c.example"))
    check("clean host -> rps untouched",
          "c.example" not in lim3._rps, str(lim3._rps.get("c.example")))
    st = lim3.waf_stats("c.example")
    check("counters: 10 succeeded", st["succeeded"] == 10, str(st))
    check("counters: 1 not_found", st["not_found"] == 1, str(st))
    check("counters: 1 server_error", st["server_error"] == 1, str(st))


def t_wait_jitter():
    async def go():
        lim = RateLimiter(default_rps=10.0)
        # non-protected: deterministic pacing
        await lim.wait("plain.example")
        n1 = lim._next["plain.example"]
        await lim.wait("plain.example")
        gap = lim._next["plain.example"] - n1
        plain_ok = abs(gap - 0.1) < 0.02

        # protected: jittered spacing (seeded for determinism)
        import random
        random.seed(7)
        lim.note_result("waf.example", classify_response(
            resp(403, {"cf-ray": "a"}, CF_CHALLENGE, url="https://waf.example/")))
        gaps = []
        prev = None
        for _ in range(6):
            await lim.wait("waf.example")
            cur = lim._next["waf.example"]
            if prev is not None:
                gaps.append(cur - prev)
            prev = cur
        jittered = len(set(round(g, 3) for g in gaps)) > 1
        return plain_ok, jittered, gaps
    plain_ok, jittered, gaps = asyncio.run(go())
    check("non-waf wait: deterministic 0.1s gap", plain_ok)
    check("waf wait: jittered gaps", jittered, str([round(g, 3) for g in gaps]))


def t_fetch_integration():
    async def go():
        def handler(request):
            if "waf.example" in str(request.url):
                return resp(403, {"cf-ray": "zz", "server": "cloudflare"},
                            CF_CHALLENGE, url=str(request.url))
            return resp(200, {}, "<html>Example Domain</html>",
                        url=str(request.url))
        transport = httpx.MockTransport(handler)
        lim = RateLimiter(default_rps=25.0)
        async with httpx.AsyncClient(transport=transport) as client:
            r1 = await fetch(client, lim, "GET", "https://waf.example/")
            r2 = await fetch(client, lim, "GET", "https://example.com/")
        return lim, r1.status_code, r2.status_code
    lim, s1, s2 = asyncio.run(go())
    check("fetch: waf host got 403", s1 == 403)
    check("fetch: clean host got 200", s2 == 200)
    check("fetch: waf host in graceful mode", lim.waf_active("waf.example"))
    check("fetch: clean host untouched", not lim.waf_active("example.com"))
    st = lim.waf_stats("waf.example")
    check("fetch: blocked counted", st["blocked"] >= 1, str(st))
    check("fetch: vendor Cloudflare", st["vendor"] == "Cloudflare", str(st["vendor"]))


def t_runner_suppression():
    # _run_plugin suppresses aggressive plugins on WAF hosts, runs the rest.
    from app.plugins.base import Ctx, Plugin, PluginResult, Target
    from app import runner as R

    events = []
    async def fake_emit(run_id, event, data):
        events.append((event, data))
    R._emit = fake_emit  # no DB in unit test

    ran = []
    class AggPlugin(Plugin):
        id = "aggtest"; label = "t"; aggressive = True
        async def run(self, target, ctx):
            ran.append("agg"); return self._ok([])
    class LightPlugin(Plugin):
        id = "lighttest"; label = "t"
        async def run(self, target, ctx):
            ran.append("light"); return self._ok([])

    async def go():
        lim = RateLimiter(default_rps=25.0)
        lim.note_result("waf.example", classify_response(
            resp(403, {"cf-ray": "a"}, CF_CHALLENGE, url="https://waf.example/")))
        async with httpx.AsyncClient(trust_env=False) as http:
            ctx = Ctx(run_id="r1", mode="active", http=http, cache=None,
                      keys={}, limiter=lim, shared={})
            t = Target(raw="waf.example", type="domain", normalized="waf.example")
            r_agg = await R._run_plugin(AggPlugin(), t, ctx)
            r_light = await R._run_plugin(LightPlugin(), t, ctx)
            # non-waf host: aggressive plugin runs normally
            t2 = Target(raw="example.com", type="domain", normalized="example.com")
            r_agg2 = await R._run_plugin(AggPlugin(), t2, ctx)
        return r_agg, r_light, r_light, r_agg2, events
    r_agg, r_light, _, r_agg2, events = asyncio.run(go())
    check("suppressed: aggressive plugin did not run", ran.count("agg") == 1, str(ran))
    check("suppressed: note names vendor",
          "Cloudflare" in r_agg.reason, r_agg.reason[:80])
    check("suppressed: status ok (no skips ever)", r_agg.status.value == "ok")
    check("light plugin ran on waf host", "light" in ran)
    check("waf_detected event emitted",
          any(e == "waf_detected" for e, _ in events),
          str([e for e, _ in events]))
    wd = [d for e, d in events if e == "waf_detected"][0]
    check("waf_detected carries blocked/succeeded",
          "blocked" in wd and "succeeded" in wd, str(wd))
    check("waf_probe_suppressed event emitted",
          any(e == "waf_probe_suppressed" for e, _ in events))


