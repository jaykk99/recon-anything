"""Wireshark dissector Lua generator: consumes a discovered
protocol layout (operator-supplied capture-analysis result,
.proto/schema finding, or a custom-port service spec) and
generates a Wireshark Lua dissector script - Proto fields,
dissector function skeleton, and dissector-table port bindings -
delivered inside a report finding as an artifact.

Pure code generation over supplied scan data, keyless; the
generated script is never executed by this plugin.
"""
from __future__ import annotations

import json
import re
from typing import Any, Dict, List

from .base import Cost, Ctx, Plugin, PluginResult, Target
from ._cat9_common import collect, text_of

_TYPES = {"uint8": "uint8", "uint16": "uint16", "uint32": "uint32",
          "uint64": "uint64", "string": "string", "bytes": "bytes",
          "bool": "bool", "ipv4": "ipv4", "float": "float",
          "double": "double"}


def parse_layout(data: bytes) -> Dict[str, Any]:
    """{name, ports:[int], fields:[{name,type,size}]} or {}."""
    text = text_of(data)
    if not text:
        return {}
    try:
        obj = json.loads(text)
    except Exception:
        obj = None
    if isinstance(obj, dict) and (
            "fields" in obj or "protocol" in obj or "name" in obj):
        fields = []
        for f in obj.get("fields", []) or []:
            if isinstance(f, dict) and f.get("name"):
                fields.append({
                    "name": str(f["name"]),
                    "type": _TYPES.get(str(
                        f.get("type", "bytes")).lower(), "bytes"),
                    "size": int(f.get("size") or 0)
                    if str(f.get("size") or "").isdigit() else 0})
        ports = []
        for p in obj.get("ports", []) or []:
            try:
                ports.append(int(p))
            except Exception:
                continue
        return {"name": re.sub(r"[^A-Za-z0-9_]", "_",
                                str(obj.get("name")
                                    or obj.get("protocol")
                                    or "customproto")),
                "ports": ports, "fields": fields,
                "transport": str(obj.get("transport", "tcp"))}
    # .proto-like layout: message fields become dissector fields.
    fields = []
    for m in re.finditer(
            r"(?m)^\s*(?:repeated\s+)?(string|bytes|bool|int32|int64|"
            r"uint32|uint64|sint32|fixed32|fixed64|double|float)\s+"
            r"(\w+)\s*=\s*\d+", text):
        tmap = {"int32": "int32", "sint32": "int32",
                "fixed32": "uint32", "fixed64": "uint64"}
        typ = tmap.get(m.group(1), m.group(1))
        fields.append({"name": m.group(2),
                       "type": _TYPES.get(typ, "bytes"), "size": 0})
    name_m = re.search(r"(?m)^\s*message\s+(\w+)", text)
    if fields or name_m:
        return {"name": (name_m.group(1) if name_m else "customproto"),
                "ports": [], "fields": fields, "transport": "tcp"}
    return {}


def generate_lua(layout: Dict[str, Any]) -> str:
    """Render the Lua dissector for a parsed layout. '' if unusable."""
    if not layout or len(layout.get("fields") or []) < 2:
        return ""
    name = layout["name"] or "customproto"
    lines = [
        f"-- Wireshark Lua dissector for {name}",
        "-- Generated by ReconAnything from a supplied protocol "
        "layout.",
        "-- Install: place in Wireshark's personal plugins folder.",
        f'local p_{name} = Proto("{name.lower()}", "{name} '
        'protocol")',
        "local f = p_" + name + ".fields",
    ]
    for fld in layout["fields"]:
        lines.append(
            f'f.{fld["name"]} = ProtoField.{fld["type"]}('
            f'"{name.lower()}.{fld["name"]}", "{fld["name"]}")')
    lines += [
        f"function p_{name}.dissector(buffer, pinfo, tree)",
        f'    pinfo.cols.protocol = "{name.upper()}"',
        f'    local subtree = tree:add(p_{name}, buffer(), '
        f'"{name} data")',
        "    local offset = 0",
    ]
    for fld in layout["fields"]:
        size = fld.get("size") or 0
        if size:
            lines.append(
                f'    subtree:add(f.{fld["name"]}, '
                f'buffer(offset, {size}))')
            lines.append(f"    offset = offset + {size}")
        else:
            lines.append(
                f'    subtree:add(f.{fld["name"]}, '
                f'buffer(offset))')
            lines.append("    offset = buffer:len()")
    lines.append("end")
    table = "tcp.port" if layout.get("transport", "tcp") != "udp" \
        else "udp.port"
    for port in layout.get("ports") or []:
        lines.append(
            f'local t = DissectorTable.get("{table}")')
        lines.append(f't:add({port}, p_{name})')
    return "\n".join(lines) + "\n"


def analyze(data: bytes, name: str = "") -> List[Dict[str, Any]]:
    layout = parse_layout(data)
    lua = generate_lua(layout)
    if not lua:
        return []
    return [{
        "key": "wireshark_dissector_generated", "severity": "low",
        "value": f"Generated a Wireshark Lua dissector for "
                 f"protocol '{layout['name']}': "
                 f"{len(layout['fields'])} fields, port bindings "
                 f"{layout.get('ports') or 'none'} "
                 f"({len(lua)} bytes of Lua in evidence)",
        "evidence": {"protocol": layout["name"],
                     "fields": len(layout["fields"]),
                     "ports": layout.get("ports") or [],
                     "lua": lua,
                     "remediation": "Save the Lua from this "
                     "finding's evidence as <protocol>.lua in "
                     "Wireshark's plugins folder to decode this "
                     "custom protocol in captures."}}]


class WiresharkDissectorLuaGeneratorPlugin(Plugin):
    id = "wireshark_dissector_lua_generator"
    label = "Wireshark Dissector Lua Generator"
    accepts = ["domain", "url", "ip", "artifact", "file"]
    passive = True
    cost = Cost.FREE
    group = "network"
    phase = 2
    description = ("Generates a Wireshark Lua dissector (Proto "
                   "fields + port bindings) from a supplied protocol "
                   "layout / .proto schema. Pure generation; nothing "
                   "is executed against a target.")
    timeout_s = 30

    async def run(self, target: Target, ctx: Ctx) -> PluginResult:
        try:
            got = collect(self, target, ctx, analyze, "infra",
                          ("protocol_layouts", "proto_schemas"))
            if got is not None:
                return got
            return self._ok([], "no supplied protocol layout in "
                            "ctx.shared; nothing to generate from")
        except Exception as exc:
            return self._ok([], f"analysis degraded: {exc}"[:200])
